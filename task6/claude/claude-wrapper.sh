#!/bin/sh
# =============================================================================
#  Обёртка над бинарником Claude Code CLI (claude-real).
#
#  В образе настоящий CLI переименован в claude-real, а в PATH кладётся этот
#  скрипт. Так любой запуск `claude` (интерактивный или `claude -p`) проходит
#  через ограничение списка инструментов.
#
#  Зачем: штатный каталог Claude Code — 15+ инструментов (Task, MCP, Skill,
#  агенты и т.д.). Локальная модель 12B путается и начинает вызывать
#  несуществующие имена или печатать JSON/XML вместо настоящего tool_use.
#  Оставляем только то, что нужно для работы с /workspace:
#    Bash, Read, Glob, Grep, Edit, Write
#
#  Если пользователь уже передал --tools, ничего не подставляем.
#  sed в Dockerfile снимает CRLF — скрипт должен быть UNIX-строками.
# =============================================================================

has_tools=0
for arg in "$@"; do
  case "$arg" in
    --tools|--tools=*) has_tools=1 ;;
  esac
done

if [ "$has_tools" -eq 0 ]; then
  set -- --tools "Bash,Read,Glob,Grep,Edit,Write" "$@"
fi

exec claude-real "$@"
